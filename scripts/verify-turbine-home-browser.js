// Playwright CLI browser test. Use an isolated localhost profile, never a user's session.
async (page) => {
  if (!page.url().startsWith('http://127.0.0.1:5173/')) throw new Error('Only run against localhost');
  const frame = page.frameLocator('iframe'), checks = [];
  const check = (name, okay) => { if (!okay) throw new Error(name); checks.push(name); };
  const library = () => page.frames().find(value => value.url().includes('/modules/cfx-post-library/app.html'));
  await frame.getByRole('heading', { name: '机组资料库', exact: true }).waitFor();
  await library().waitForFunction(() => !document.querySelector('#newTurbineHomeBtn').disabled);
  await library().evaluate(async () => {
    const fixture = CfxTurbineWorkspaces.getSnapshot();
    if (fixture.turbineWorkspaces[0].database.items.length !== 4) throw new Error('Expected isolated example fixture');
    fixture.turbineWorkspaces = fixture.turbineWorkspaces.slice(0, 2);
    fixture.turbineWorkspaces[0].name = 'YX'; fixture.turbineWorkspaces[1].name = 'ZL';
    applyIncomingDatabase(fixture, 'replace', 'reset isolated card test');
    await CfxCacheDiagnostics.forcePersist();
  });
  check('外层模块打开显示卡片首页', await library().evaluate(() => CfxTurbineWorkspaces.isHome() && document.querySelector('.app').inert));
  await frame.getByRole('button', { name: '进入 YX 资料库', exact: true }).click();
  await library().waitForFunction(() => !CfxTurbineWorkspaces.isHome());
  check('卡片进入YX原资料', await library().evaluate(() => state.items.length === 4 && document.querySelector('#currentTurbineWorkspaceName').textContent === 'YX'));
  check('库内移除重复选择和新建改名控件', await library().evaluate(() => !document.querySelector('#turbineWorkspaceSelect, #addTurbineWorkspaceBtn, #renameTurbineWorkspaceBtn')));
  await frame.getByRole('button', { name: '返回资料库首页', exact: false }).click();
  await library().waitForFunction(() => CfxTurbineWorkspaces.isHome());
  await frame.getByRole('button', { name: '进入 ZL 资料库', exact: true }).click();
  await library().waitForFunction(() => !CfxTurbineWorkspaces.isHome());
  check('另一个卡片进入独立空库', await library().evaluate(() => state.items.length === 0));
  await page.getByRole('button', { name: 'CFX-Post 公式与命令库', exact: true }).click();
  await library().waitForFunction(() => CfxTurbineWorkspaces.isHome());
  check('再次点击外层模块返回卡片首页', await frame.getByRole('heading', { name: '机组资料库', exact: true }).isVisible());
  await frame.getByRole('button', { name: '＋ 新建资料库', exact: true }).click();
  await frame.getByRole('textbox', { name: '机组名称', exact: true }).fill('HX');
  await frame.getByRole('button', { name: '创建资料库', exact: true }).click();
  await library().waitForFunction(() => !document.querySelector('#newTurbineHomeBtn').disabled && CfxTurbineWorkspaces.getSnapshot().turbineWorkspaces.length === 3);
  check('新建后首页增加卡片不自动进入', await frame.getByRole('button', { name: '进入 HX 资料库', exact: true }).isVisible());
  await frame.getByRole('button', { name: '重命名 YX 资料库', exact: true }).click();
  await frame.getByRole('textbox', { name: '机组名称', exact: true }).fill('YX机组');
  await frame.getByRole('button', { name: '保存名称', exact: true }).click();
  await frame.getByRole('button', { name: '进入 YX机组 资料库', exact: true }).waitFor();
  check('首页可给非当前资料库改名', await frame.getByRole('button', { name: '进入 YX机组 资料库', exact: true }).isVisible());
  check('改名不改变当前库及原资料', await library().evaluate(() => state.items.length === 0 && CfxTurbineWorkspaces.getSnapshot().turbineWorkspaces.find(value => value.name === 'YX机组').database.items.length === 4));
  await frame.getByRole('searchbox', { name: '查找资料库', exact: true }).fill('ZL');
  check('名称搜索只显示匹配卡片', await frame.locator('[data-enter-turbine]').count() === 1);
  await frame.getByRole('searchbox', { name: '查找资料库', exact: true }).fill('不存在');
  check('无匹配状态可见', await frame.getByText('没有找到匹配的资料库', { exact: true }).isVisible());
  await frame.getByRole('searchbox', { name: '查找资料库', exact: true }).fill('');
  await frame.getByRole('button', { name: '进入 HX 资料库', exact: true }).click();
  await library().waitForFunction(() => !CfxTurbineWorkspaces.isHome());
  await frame.getByRole('button', { name: '新建条目', exact: true }).click();
  await frame.locator('#itemTitle').fill('HX未保存命令');
  await frame.locator('#cclCode').fill('PLANE: HX\nEND');
  await frame.getByRole('button', { name: '返回资料库首页', exact: false }).click();
  await frame.getByRole('dialog').getByRole('button', { name: '取消', exact: true }).click();
  await library().waitForFunction(() => !document.querySelector('#backToTurbineHomeBtn').disabled);
  check('取消返回保留未保存编辑', await frame.locator('#itemTitle').inputValue() === 'HX未保存命令');
  await page.getByRole('button', { name: 'CFX-Post 公式与命令库', exact: true }).click();
  await frame.getByRole('dialog').getByRole('button', { name: '保存并继续', exact: true }).click();
  await library().waitForFunction(() => CfxTurbineWorkspaces.isHome() && !document.querySelector('#newTurbineHomeBtn').disabled);
  check('保存并返回更新卡片数量', await frame.locator('[data-enter-turbine]').filter({ hasText: 'HX' }).innerText().then(value => value.includes('1 条资料')));
  const downloadPromise = page.waitForEvent('download');
  await frame.getByRole('button', { name: '备份全部', exact: true }).click();
  const backup = await downloadPromise;
  await backup.saveAs('E:/浏览器及软件下载/CODEX/成果储存/冲击式水轮机工具箱储存/公式命令库卡片首页_2026-09-30/过程文件/合成测试资料库备份.json');
  check('首页完整备份下载成功', (await backup.failure()) === null);
  await library().evaluate(async () => { await CfxCacheDiagnostics.forcePersist(); state.github.dirty = false; });
  await page.reload();
  await frame.getByRole('button', { name: '进入 HX 资料库', exact: true }).waitFor();
  check('外层页面重新打开仍显示卡片首页', await library().evaluate(() => CfxTurbineWorkspaces.isHome()));
  check('卡片名称和独立数据刷新后保留', await frame.locator('[data-enter-turbine]').count() === 3 && await library().evaluate(() => CfxTurbineWorkspaces.getSnapshot().turbineWorkspaces.find(value => value.name === 'HX').database.items.length === 1));
  await frame.getByRole('button', { name: '进入 HX 资料库', exact: true }).click();
  await library().waitForFunction(() => !CfxTurbineWorkspaces.isHome());
  await frame.getByRole('button', { name: 'CST 文件资料库', exact: true }).click();
  await frame.getByRole('heading', { name: 'CST 文件资料库 · HX', exact: true }).waitFor();
  await frame.getByRole('button', { name: '返回公式与命令库', exact: false }).click();
  await frame.getByRole('button', { name: '返回资料库首页', exact: false }).waitFor();
  check('CST返回仍在所属功能库', await library().evaluate(() => !CfxTurbineWorkspaces.isHome() && state.items[0].title === 'HX未保存命令'));
  await frame.getByRole('button', { name: '返回资料库首页', exact: false }).click();
  await frame.getByRole('heading', { name: '机组资料库', exact: true }).waitFor();
  await page.setViewportSize({ width: 1910, height: 920 });
  return { passed: checks.length, checks };
}
