import assert from 'node:assert/strict';
import vm from 'node:vm';
import { readFileSync } from 'node:fs';
const sandbox = { URLSearchParams };
vm.createContext(sandbox);
vm.runInContext(readFileSync(new URL('../public/modules/cfx-post-library/turbine-workspaces-core.js', import.meta.url), 'utf8'), sandbox);
const m = sandbox.CfxTurbineWorkspaceModel;
const copy = value => JSON.parse(JSON.stringify(value));
const normalizeSingle = value => copy({ items: Array.isArray(value) ? value : value.items || [], categories: value.categories || [], folders: value.folders || [], defaultCategory: value.defaultCategory || '未分类' });
const singleEqual = (a, b) => JSON.stringify(normalizeSingle(a)) === JSON.stringify(normalizeSingle(b));
const mergeSingle = (b, l, r) => singleEqual(l, b) ? { merged: r, conflicts: [] } : singleEqual(r, b) || singleEqual(l, r) ? { merged: l, conflicts: [] } : { merged: null, conflicts: [{ id: 'shared-id', name: '重名资料', fields: ['title'] }] };
const initialSingle = (l, r) => singleEqual(l, r) ? { merged: l, conflicts: [] } : { merged: { ...l, items: [...l.items, ...r.items] }, conflicts: [] };
const options = { normalizeSingle, singleEqual, mergeSingle, initialSingle };
const original = { items: [{ id: 'shared-id', title: 'YX资料' }], categories: ['公式'], folders: [{ id: 'folder-1', name: '喷嘴', parentId: 'parent' }] };
const migrated = m.normalize(original, normalizeSingle);
assert.equal(migrated.turbineWorkspaces[0].id, m.LEGACY_ID);
assert.equal(migrated.items[0].title, 'YX资料');
assert.equal(migrated.folders[0].parentId, 'parent');
const base = copy(migrated); base.turbineWorkspaces[0].name = 'YX';
base.turbineWorkspaces.push({ id: 'zl', name: 'ZL', database: normalizeSingle({ items: [{ id: 'shared-id', title: 'ZL资料' }] }) });
const local = copy(base), remote = copy(base);
local.turbineWorkspaces[0].database.items[0].title = 'YX本地编辑';
remote.turbineWorkspaces[1].database.items[0].title = 'ZL远端编辑';
const merged = m.merge(base, local, remote, options);
assert.equal(merged.conflicts.length, 0);
assert.equal(merged.merged.turbineWorkspaces[0].database.items[0].title, 'YX本地编辑');
assert.equal(merged.merged.turbineWorkspaces[1].database.items[0].title, 'ZL远端编辑');
assert.equal(base.turbineWorkspaces[0].database.items[0].title, 'YX资料');
assert.equal(m.equal(base, copy(base), normalizeSingle, singleEqual), true);
assert.equal(m.equal(base, remote, normalizeSingle, singleEqual), false);
remote.turbineWorkspaces[0].database.items[0].title = 'YX冲突编辑';
assert.match(m.merge(base, local, remote, options).conflicts[0].name, /YX/);
const renamed = copy(base); renamed.turbineWorkspaces[1].name = 'ZL-新名称';
assert.equal(m.merge(base, base, renamed, options).merged.turbineWorkspaces[1].name, 'ZL-新名称');
const added = copy(base); added.turbineWorkspaces.push({ id: 'other', name: '其他机组', database: normalizeSingle({ items: [] }) });
assert.equal(m.merge(base, added, base, options).merged.turbineWorkspaces.length, 3);
const deleted = copy(base); deleted.turbineWorkspaces.pop();
assert.equal(m.merge(base, deleted, base, options).merged.turbineWorkspaces.length, 1);
assert.equal(m.merge(base, deleted, remote, options).conflicts.length, 1);
assert.equal(m.scopedKey('cst', m.LEGACY_ID), 'cst');
assert.equal(m.scopedKey('cst', 'zl'), 'cst:zl');
assert.throws(() => m.normalize({ turbineWorkspaces: [] }, normalizeSingle));
assert.throws(() => m.normalize({ turbineWorkspaces: [{ id: 'zl', name: '', database: original }] }, normalizeSingle));
assert.throws(() => m.normalize({ turbineWorkspaces: [...base.turbineWorkspaces, base.turbineWorkspaces[0]] }, normalizeSingle));
const pref = m.merge(base, local, remote, { ...options, preferLocal: true, mergeSingle: (b, l) => ({ merged: l, conflicts: [] }) });
assert.equal(pref.merged.turbineWorkspaces[0].database.items[0].title, 'YX本地编辑');
console.log('多机组数据模型：旧库迁移、独立编辑、命名、合并冲突、增删、句柄隔离及输入校验全部通过。');
