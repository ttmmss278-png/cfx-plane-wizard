import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import vm from 'node:vm';
const html=readFileSync(new URL('../public/modules/plane-wizard/index.html',import.meta.url),'utf8');
const defaults=vm.runInNewContext(`(${html.match(/const If="cst-circle-section-gen-v1",ra=(\{[\s\S]*?\}),BE=/)[1]})`);
const values=new Map(),events=[];
const sandbox={localStorage:{getItem:k=>values.get(k)||null,setItem:(k,v)=>values.set(k,v)},CustomEvent:class{constructor(type,init){this.type=type;this.detail=init.detail;}},dispatchEvent:e=>events.push(e)};
vm.createContext(sandbox);vm.runInContext(readFileSync(new URL('../public/modules/plane-wizard/parameter-memory.js',import.meta.url),'utf8'),sandbox);
const m=sandbox.PlaneParameterMemory,copy=v=>JSON.parse(JSON.stringify(v));
const savedKey='cst-circle-section-gen-v1',draftKey='cst-circle-section-gen-draft-v1';
assert.deepEqual(copy(m.read(defaults)),copy(defaults));
values.set(savedKey,JSON.stringify({domain:'B1',prefix:'PZ',count:8,sixDir:'cw',sixEnabled:true}));
assert.equal(m.read(defaults).domain,'B1');assert.equal(m.read(defaults).unit,'m');
const migrated=m.read(defaults);assert.equal(m.saveDraft(migrated,defaults),true);
const draft={...copy(migrated),domain:'B2',C:[-1.2,0,3],distance:0,includeFirst:false,sixBase:2,nozzleNaming:true,cfxTemplate:'PLANE:{name}\n  Domain List = {domain}\nEND'};
assert.equal(m.saveDraft(draft,defaults),true);
assert.deepEqual(copy(m.read(defaults)),draft);
assert.equal(JSON.parse(values.get(savedKey)).domain,'B1'); // Automatic edits do not replace the restore point.
assert.equal(m.saveManual(draft,defaults),true);
assert.equal(m.saveDraft({...draft,domain:'B3',count:12},defaults),true);
assert.equal(m.read(defaults).domain,'B3');assert.equal(m.readManual(defaults).domain,'B2');
assert.equal(m.saveDraft({...draft,distance:NaN,C:[NaN,5,Infinity]},defaults),true);
assert.equal(m.read(defaults).distance,0);assert.deepEqual(copy(m.read(defaults).C),[-1.2,5,3]);
const manualRaw=values.get(savedKey);
values.set(draftKey,'{"domain":');assert.equal(m.read(defaults).domain,'B2');
assert.equal(m.saveDraft(draft,defaults),true);assert.equal(values.get(draftKey+'-invalid-backup'),'{"domain":');
assert.equal(values.get(savedKey),manualRaw);
values.set(draftKey,JSON.stringify({domain:'B4',C:[1,2],sixEnabled:'false',count:'8'}));
const invalid=m.read(defaults);assert.equal(invalid.domain,'B4');assert.deepEqual(copy(invalid.C),copy(defaults.C));assert.equal(invalid.count,defaults.count);assert.equal(invalid.sixEnabled,defaults.sixEnabled);
