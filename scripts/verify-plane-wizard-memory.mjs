assert.equal(m.saveDraft(draft,defaults),false);assert.equal(events.at(-1).detail.saved,false);
assert.equal(m.saveManual(draft,defaults),false);
sandbox.localStorage.getItem=()=>{throw Error('SecurityError');};
assert.deepEqual(copy(m.read(defaults)),copy(defaults));
assert.ok(html.indexOf('parameter-memory.js')<html.indexOf('<script type="module"'));
assert.match(html,/useState\(\(\)=>globalThis\.PlaneParameterMemory\.read\(ra\)\)/);
assert.match(html,/PlaneParameterMemory\.saveDraft\(e,ra\)/);
assert.match(html,/role:"status",children:memoryStatus/);
console.log('PASS: automatic restore, legacy manual save migration, all parameter types, zero/false, separate restore point, invalid edit retention, corrupt draft backup and blocked storage failure.');
